"""Financial fact graph + community builder over the 10-K chunk corpus.

Two layers, both persisted in one JSON artifact:

1. Fact graph (typed, deterministic). Nodes: Company, Filing, FinancialMetric,
   MetricValue, Chunk. MetricValue nodes are extracted ONLY by deterministic
   table parsing — an LLM never contributes numbers to this layer. Year
   columns are detected from table headers so multi-year statements produce
   one value node per (ticker, metric, year), each with provenance edges to
   the exact chunk it was parsed from.

2. Community layer (GraphRAG-style). Entities (companies + metrics) that
   co-occur in chunks form an undirected weighted graph; Louvain community
   detection groups them. Each community carries a deterministic profile
   (members, supporting chunk ids). Optional LLM summaries are generated by
   `summarize_communities` and cached — never required for queries.
"""

from __future__ import annotations

import json
import logging
import re
from pathlib import Path
from typing import Any

import networkx as nx

logger = logging.getLogger(__name__)

# Canonical metrics and the surface phrases that map to them.
KNOWN_METRICS = {
    "total net sales": "Net Sales",
    "net sales": "Net Sales",
    "total net revenue": "Total Revenue",
    "total revenue": "Total Revenue",
    "net revenues": "Total Revenue",
    "revenue": "Total Revenue",
    "net income": "Net Income",
    "net earnings": "Net Income",
    "operating income": "Operating Income",
    "operating profit": "Operating Income",
    "income from operations": "Operating Income",
    "gross margin": "Gross Margin",
    "gross profit": "Gross Profit",
    "cost of sales": "Cost of Sales",
    "cost of revenue": "Cost of Revenue",
    "operating expenses": "Operating Expenses",
    "research and development": "R&D Expense",
    "r&d": "R&D Expense",
    "selling, general and administrative": "SG&A Expense",
    "total assets": "Total Assets",
    "total liabilities": "Total Liabilities",
    "total stockholders' equity": "Stockholders Equity",
    "total shareholders' equity": "Stockholders Equity",
    "cash and cash equivalents": "Cash & Cash Equivalents",
    "cash generated by operating activities": "Operating Cash Flow",
    "net cash provided by operating activities": "Operating Cash Flow",
    "diluted earnings per share": "Diluted EPS",
    "diluted net income per share": "Diluted EPS",
    "diluted eps": "Diluted EPS",
    "free cash flow": "Free Cash Flow",
    "capital expenditures": "Capital Expenditures",
}

# Longest phrases first so "total net sales" wins over "net sales".
_METRIC_PHRASES = sorted(KNOWN_METRICS, key=len, reverse=True)

_YEAR_RE = re.compile(r"\b(19[6-9]\d|20[0-4]\d)\b")
_NUM_RE = re.compile(r"([\d,]+(?:\.\d+)?)")
_CELL_DECORATIONS = set("$€£() %\t")


_FOOTNOTE_RE = re.compile(r"\s*\(\d+\)\s*$")


def _match_metric(label: str) -> str | None:
    """Match a row label to a canonical metric.

    Anchored matching only: the phrase must start the label (after
    stripping footnote markers), so "Percentage of total net sales" does
    NOT become a Net Sales fact. Long trailing qualifiers (>30 chars) are
    treated as different line items.
    """
    low = _FOOTNOTE_RE.sub("", label.lower().strip()).rstrip(": ")
    for phrase in _METRIC_PHRASES:
        if low == phrase or (low.startswith(phrase) and len(low) - len(phrase) <= 30):
            return KNOWN_METRICS[phrase]
    return None


def _parse_cell(cell: str) -> tuple[float, bool] | None:
    """Parse one table cell into (value, is_percent); None if not numeric.

    Handles the usual 10-K decorations in any order: $, %, and parentheses
    for negative values — e.g. "$(1,234)", "(1,234)", "46.9%".
    """
    c = cell.strip()
    if not c or c in {"—", "-", "$"}:
        return None
    m = _NUM_RE.search(c)
    if not m:
        return None
    leftover = c.replace(m.group(1), "", 1)
    if any(ch not in _CELL_DECORATIONS for ch in leftover):
        return None  # prose mixed into the cell — not a clean number
    try:
        value = float(m.group(1).replace(",", ""))
    except ValueError:
        return None
    if "(" in c and ")" in c:
        value = -value
    return value, c.rstrip().endswith("%")


def _table_blocks(lines: list[str]) -> list[tuple[int, list[str]]]:
    """Split lines into (start_line_no, lines) runs of pipe-delimited lines."""
    blocks: list[tuple[int, list[str]]] = []
    current: list[str] = []
    start = 0
    for i, line in enumerate(lines):
        if "|" in line:
            if not current:
                start = i
            current.append(line)
        elif current:
            blocks.append((start, current))
            current = []
    if current:
        blocks.append((start, current))
    return blocks


def _year_headers(lines: list[str]) -> list[tuple[int, list[str]]]:
    """(line_no, years) for every pipe line carrying >=2 fiscal years."""
    headers = []
    for i, line in enumerate(lines):
        if "|" in line:
            found = _YEAR_RE.findall(line)
            if len(found) >= 2:
                headers.append((i, found))
    return headers


def _unit_near(lines: list[str], block_start: int, default: str) -> str:
    """Unit from the nearest annotation above the block (statements carry
    several tables with different units in one chunk, so chunk-wide scans
    mislabel). When a line carries several phrases — "(In millions, except
    shares in thousands...)" — the first one is the primary unit."""
    for j in range(block_start, max(-1, block_start - 20), -1):
        low = lines[j].lower()
        candidates = []
        for phrase, unit in (("in thousands", "USD_TH"),
                             ("in millions", "USD_M"),
                             ("in billions", "USD_B")):
            pos = low.find(phrase)
            if pos >= 0:
                candidates.append((pos, unit))
        if candidates:
            return min(candidates)[1]
    return default


class FinancialGraphBuilder:
    """Builds and persists the fact graph + community layer."""

    def __init__(self, graph: nx.DiGraph | None = None) -> None:
        self.graph = graph if graph is not None else nx.DiGraph()
        self.communities: list[dict[str, Any]] = []

    # ------------------------------------------------------------ fact graph

    def add_company(self, ticker: str, name: str | None = None) -> str:
        cid = f"company:{ticker.upper()}"
        if not self.graph.has_node(cid):
            self.graph.add_node(cid, label="Company", ticker=ticker.upper(),
                                name=name or ticker.upper())
        return cid

    def add_filing(self, ticker: str, fiscal_year: int | str, form: str = "10-K") -> str:
        comp_id = self.add_company(ticker)
        fid = f"filing:{ticker.upper()}_{fiscal_year}_{form}"
        if not self.graph.has_node(fid):
            self.graph.add_node(fid, label="Filing", ticker=ticker.upper(),
                                fiscal_year=str(fiscal_year), form=form)
            self.graph.add_edge(comp_id, fid, relation="REPORTED_IN")
        return fid

    def add_metric_value(
        self,
        ticker: str,
        fiscal_year: int | str,
        metric_name: str,
        value: float,
        unit: str = "USD_M",
        chunk_id: str | None = None,
        priority: int = 0,
    ) -> str:
        """Add one (ticker, metric, year) -> value fact with provenance.

        priority ranks the source section (financial statements beat MD&A);
        a higher-priority extraction replaces a lower one.
        """
        filing_id = self.add_filing(ticker, fiscal_year)
        metric_id = f"metric:{metric_name.lower().replace(' ', '_').replace('&', 'and')}"
        if not self.graph.has_node(metric_id):
            self.graph.add_node(metric_id, label="FinancialMetric", name=metric_name)

        val_id = (f"val:{ticker.upper()}:{metric_name.lower().replace(' ', '_')}"
                  f":{fiscal_year}")
        if self.graph.has_node(val_id):
            if priority <= self.graph.nodes[val_id].get("_priority", 0):
                return val_id
            self.graph.nodes[val_id].update(
                value=value, unit=unit, chunk_id=chunk_id, _priority=priority)
            return val_id
        self.graph.add_node(val_id, label="MetricValue", ticker=ticker.upper(),
                            metric=metric_name, fiscal_year=str(fiscal_year),
                            value=value, unit=unit, chunk_id=chunk_id,
                            _priority=priority)
        self.graph.add_edge(filing_id, val_id, relation="RECORDED_VALUE")
        self.graph.add_edge(metric_id, val_id, relation="CONTAINS_METRIC")
        if chunk_id:
            chid = f"chunk:{chunk_id}"
            if not self.graph.has_node(chid):
                self.graph.add_node(chid, label="Chunk", chunk_id=chunk_id)
            self.graph.add_edge(val_id, chid, relation="CITES_CHUNK")
        return val_id

    def ingest_chunk(self, chunk: dict[str, Any]) -> int:
        """Deterministically extract (metric, year, value) facts from a chunk.

        Returns the number of value facts added.
        """
        ticker = chunk.get("ticker", "")
        fy = chunk.get("fiscal_year", "")
        text = chunk.get("text", "")
        if not ticker or not fy:
            return 0

        added = 0
        text_low = text.lower()
        # Financial statements (Item 8/8A) outrank MD&A (Item 7) which
        # outranks everything else — the same metric appears in all three.
        item = str(chunk.get("item", ""))
        priority = 2 if item in {"8", "8A"} else (1 if item in {"7", "7A"} else 0)
        # Unit annotations ("In millions") headline the statement, typically
        # outside the pipe grid, so scan the whole chunk once.
        if "in thousands" in text_low:
            chunk_unit = "USD_TH"
        elif "in billions" in text_low:
            chunk_unit = "USD_B"
        else:
            chunk_unit = "USD_M"  # 10-K statements default to millions

        lines = text.split("\n")
        headers = _year_headers(lines)

        for block_start, block in _table_blocks(lines):
            unit = _unit_near(lines, block_start, chunk_unit)

            # Year columns come from the nearest header at or above this
            # block — group labels like "Revenue:" split tables into blocks
            # but do not reset the year context.
            years: list[str] = []
            header_line = -1
            for h_line, h_years in headers:
                if h_line <= block_start + len(block):
                    years, header_line = h_years, h_line
                else:
                    break

            for i, line in enumerate(block):
                if block_start + i == header_line:
                    continue
                parts = [p.strip() for p in line.split("|") if p.strip()]
                if len(parts) < 2:
                    continue
                metric = _match_metric(parts[0])
                if metric is None:
                    continue

                parsed = [_parse_cell(p) for p in parts[1:]]
                cells = [p for p in parsed if p is not None]
                if not cells:
                    continue

                is_pct = all(p[1] for p in cells)
                row_unit = "PCT" if is_pct else unit

                if years and len(cells) <= len(years):
                    pairs = zip(years, cells)
                elif len(cells) == 1:
                    pairs = [(str(fy), cells[0])]
                else:
                    continue  # cannot attribute values to years honestly

                for year, (value, _) in pairs:
                    self.add_metric_value(ticker, year, metric, value,
                                          unit=row_unit, chunk_id=chunk.get("id"),
                                          priority=priority)
                    added += 1
        return added

    def build_from_chunks(self, chunks: list[dict[str, Any]]) -> nx.DiGraph:
        facts = 0
        for c in chunks:
            facts += self.ingest_chunk(c)
        logger.info("Fact graph: %d nodes, %d edges, %d value facts",
                    self.graph.number_of_nodes(), self.graph.number_of_edges(), facts)
        return self.graph

    # ------------------------------------------------------- community layer

    def build_communities(self, chunks: list[dict[str, Any]],
                          resolution: float = 1.0, seed: int = 42) -> list[dict[str, Any]]:
        """Louvain communities over company/metric co-occurrence in chunks."""
        cooccur = nx.Graph()
        chunk_entities: list[tuple[str, set[str]]] = []

        for c in chunks:
            ticker = c.get("ticker")
            if not ticker:
                continue
            text = c.get("text", "").lower()
            entities = {f"company:{ticker.upper()}"}
            for phrase in _METRIC_PHRASES:
                if phrase in text:
                    entities.add(f"metric:{KNOWN_METRICS[phrase]}")
            if len(entities) > 1:
                chunk_entities.append((c.get("id", ""), entities))
                for e in entities:
                    cooccur.add_node(e)
                ents = sorted(entities)
                for i, a in enumerate(ents):
                    for b in ents[i + 1:]:
                        if cooccur.has_edge(a, b):
                            cooccur[a][b]["weight"] += 1
                        else:
                            cooccur.add_edge(a, b, weight=1)

        self.communities = []
        if cooccur.number_of_edges() == 0:
            return self.communities

        groups = nx.community.louvain_communities(cooccur, weight="weight",
                                                  resolution=resolution, seed=seed)
        for idx, members in enumerate(sorted(groups, key=len, reverse=True)):
            supporting = [cid for cid, ents in chunk_entities
                          if len(ents & set(members)) >= 2]
            self.communities.append({
                "id": f"community:{idx}",
                "members": sorted(members),
                "size": len(members),
                "n_chunks": len(supporting),
                "chunk_ids": supporting[:25],
                "summary": None,
            })
        logger.info("Communities: %d detected over %d entities",
                    len(self.communities), cooccur.number_of_nodes())
        return self.communities

    def summarize_communities(self, cfg: dict[str, Any],
                              max_communities: int = 12) -> int:
        """LLM-summarize the largest communities (cached in the community dict)."""
        from ..llm import complete_with_resilience

        done = 0
        for comm in self.communities[:max_communities]:
            if comm.get("summary"):
                continue
            members = ", ".join(m.split(":", 1)[1] for m in comm["members"][:20])
            messages = [
                {"role": "system", "content": (
                    "You summarize clusters of financial entities found across "
                    "SEC 10-K filings. Two sentences, plain factual language."
                )},
                {"role": "user", "content": (
                    f"A cluster of {comm['size']} entities appears together in "
                    f"{comm['n_chunks']} filing chunks: {members}. What financial "
                    "theme does this cluster represent?"
                )},
            ]
            text, _ = complete_with_resilience(messages, cfg, role="extraction")
            comm["summary"] = text.strip()
            done += 1
        return done

    # ------------------------------------------------------------- persistence

    def save(self, path: str | Path) -> None:
        p = Path(path)
        p.parent.mkdir(parents=True, exist_ok=True)
        payload = {
            "format": "ragfilings-graph-v2",
            "graph": nx.node_link_data(self.graph),
            "communities": self.communities,
        }
        p.write_text(json.dumps(payload, ensure_ascii=False), encoding="utf-8")

    @classmethod
    def load(cls, path: str | Path) -> FinancialGraphBuilder:
        p = Path(path)
        if not p.exists():
            return cls()
        data = json.loads(p.read_text(encoding="utf-8"))
        if isinstance(data, dict) and data.get("format") == "ragfilings-graph-v2":
            builder = cls(nx.node_link_graph(data["graph"], directed=True))
            builder.communities = data.get("communities", [])
            return builder
        # Legacy v1 artifact: bare node-link dict.
        return cls(nx.node_link_graph(data, directed=True))
